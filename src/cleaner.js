// ---------- path helpers ----------

function globToRegex(seg) {
  return new RegExp('^' + seg.replace(/[.+^${}()|[\]\\]/g, '\\$&').replace(/\*/g, '.*').replace(/\?/g, '.') + '$', 'i');
}

// Expands '*' wildcards in any path segment. Returns existing paths only.
async function expand(pattern) {
  const parts = pattern.split(/[\\/]+/);
  let current = [parts[0] + '\\'];
  for (const seg of parts.slice(1)) {
    if (!seg) continue;
    const next = [];
    for (const base of current) {
      if (!/[*?]/.test(seg)) {
        const p = path.join(base, seg);
        if (fs.existsSync(p)) next.push(p);
        continue;
      }
      let entries = [];
      try { entries = await fsp.readdir(base); } catch { continue; }
      const re = globToRegex(seg);
      for (const e of entries) if (re.test(e)) next.push(path.join(base, e));
    }
    current = next;
    if (!current.length) break;
  }
  return current;
}

// Recursively collects files under dir, never following symlinks/junctions.
async function walk(dir, out, minAgeMs) {
  let entries;
  try { entries = await fsp.readdir(dir, { withFileTypes: true }); } catch { return; }
  await Promise.all(entries.map(async (e) => {
    const full = path.join(dir, e.name);
    if (e.isSymbolicLink()) return;
    if (e.isDirectory()) return walk(full, out, minAgeMs);
    try {
      const st = await fsp.lstat(full);
      if (minAgeMs && Date.now() - st.mtimeMs < minAgeMs) return;
      out.push({ path: full, size: st.size });
    } catch { /* inaccessible */ }
  }));
}

async function resolveTargets(targets) {
  const files = [];
  const dirs = [];
  for (const t of targets) {
    const minAge = t.minAgeHours ? t.minAgeHours * 3600 * 1000 : 0;
    for (const p of await expand(t.path)) {
      let st;
      try { st = await fsp.lstat(p); } catch { continue; }
      if (st.isSymbolicLink()) continue;
      if (t.type === 'contents' && st.isDirectory()) { dirs.push(p); await walk(p, files, minAge); }
      else if (t.type === 'file' && st.isFile()) files.push({ path: p, size: st.size });
    }
  }
  return { files, dirs };
}

// ---------- special categories ----------

const MRU_KEYS = [
  'HKCU\\Software\\Microsoft\\Windows\\CurrentVersion\\Explorer\\RunMRU',
  'HKCU\\Software\\Microsoft\\Windows\\CurrentVersion\\Explorer\\TypedPaths',
];

const special = {
  async recycle(mode) {
    if (mode === 'scan') {
      const out = await runPS(`$s=New-Object -ComObject Shell.Application;$c=0;$z=[int64]0;foreach($i in $s.Namespace(10).Items()){$c++;$z+=[int64]$i.ExtendedProperty('Size')};"$c|$z"`);
      const [count, size] = out.split('|').map(Number);
      return { count: count || 0, size: size || 0 };
    }
    await runPS('Clear-RecycleBin -Force');
  },
  async mru(mode) {
    if (mode === 'scan') {
      let count = 0;
      for (const k of MRU_KEYS) {
        const r = await run('reg', ['query', k]);
        count += (r.stdout.match(/REG_SZ/g) || []).length;
      }
      return { count, size: 0 };
    }
    for (const k of MRU_KEYS) await run('reg', ['delete', k, '/f']);
  },
  async clipboard(mode) {
    if (mode === 'scan') return { count: clipboard.availableFormats().length ? 1 : 0, size: 0 };
    clipboard.clear();
  },
  async dns(mode) {
    if (mode === 'scan') {
      const out = await runPS('(Get-DnsClientCache | Measure-Object).Count');
      return { count: Number(out) || 0, size: 0 };
    }
    await run('ipconfig', ['/flushdns']);
  },
};

// ---------- public API ----------

const lastScan = new Map(); // category id -> { files, dirs }

async function runningProcesses() {
  const r = await run('tasklist', ['/FO', 'CSV', '/NH']);
  return new Set(r.stdout.split(/\r?\n/).map((l) => l.split('","')[0].replace(/^"/, '').toLowerCase()));
}

async function scan(group, onProgress) {
  const procs = await runningProcesses();
  const cats = CATEGORIES.filter((c) => c.group === group);
  const results = [];
  for (let i = 0; i < cats.length; i++) {
    const c = cats[i];
    onProgress?.({ current: i + 1, total: cats.length, name: c.name });
    let size = 0, count = 0;
    if (c.special) {
      try { ({ size, count } = await special[c.special]('scan')); } catch { /* ignore */ }
    } else {
      const res = await resolveTargets(c.targets);
      lastScan.set(c.id, res);
      count = res.files.length;
      size = res.files.reduce((a, f) => a + f.size, 0);
    }
    results.push({
      id: c.id, section: c.section, name: c.name, desc: c.desc, checked: c.checked, size, count,
      warning: c.proc && procs.has(c.proc) ? `${c.proc} is running — close it so locked files can be removed.` : null,
    });
  }
  return results;
}

async function removeEmptyDirs(dir, isRoot = true) {
  let entries;
  try { entries = await fsp.readdir(dir, { withFileTypes: true }); } catch { return; }
  for (const e of entries) if (e.isDirectory() && !e.isSymbolicLink()) await removeEmptyDirs(path.join(dir, e.name), false);
  if (!isRoot) { try { await fsp.rmdir(dir); } catch { /* not empty or locked */ } }
}

async function clean(ids, onProgress) {
  let freed = 0, deleted = 0, failed = 0;
  const cats = CATEGORIES.filter((c) => ids.includes(c.id));
  for (let i = 0; i < cats.length; i++) {
    const c = cats[i];
    onProgress?.({ current: i + 1, total: cats.length, name: c.name });
    if (c.special) {
      try {
        const before = await special[c.special]('scan');
        await special[c.special]('clean');
        freed += before.size; deleted += before.count;
      } catch { failed++; }
      continue;
    }
    const res = lastScan.get(c.id);
    if (!res) continue;
    for (let n = 0; n < res.files.length; n += 64) {
      await Promise.all(res.files.slice(n, n + 64).map(async (f) => {
        try { await fsp.unlink(f.path); freed += f.size; deleted++; } catch { failed++; }
      }));
    }
    for (const d of res.dirs) await removeEmptyDirs(d);
    lastScan.delete(c.id);
  }
  return { freed, deleted, failed };
}

module.exports = { scan, clean };
