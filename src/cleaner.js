function chromiumTargets(root, subpaths, type) {
  // Profiles are "Default", "Profile 1", "Profile 2", ...
  return ['Default', 'Profile *'].flatMap((prof) =>
    subpaths.map((s) => ({ path: path.join(root, prof, s), type }))
  );
}

